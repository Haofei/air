#[derive(Debug, Error)]
pub enum LangGraphBackendError {
    #[error("LangGraph backend only supports state_machine workflow lowering")]
    UnsupportedWorkflow,

    #[error("unsupported state_machine condition {0}")]
    UnsupportedCondition(String),

    #[error("unsupported expression {0}")]
    UnsupportedExpr(String),

    #[error("failed to serialize literal JSON: {0}")]
    Json(#[from] serde_json::Error),

    #[error("failed to parse AIR module: {0}")]
    ModuleParse(#[from] air_parser::ParseError),

    #[error(transparent)]
    Linker(#[from] air_linker::LinkerError),

    #[error("run plan references unknown module {0}")]
    UnknownModule(String),

    #[error("module {module} failed verification: {diagnostics:?}")]
    ModuleVerify {
        module: String,
        diagnostics: Vec<air_core::Diagnostic>,
    },
}

pub fn lower_module(module: &AirModule) -> Result<String, LangGraphBackendError> {
    let Workflow::StateMachine(_) = &module.workflow else {
        return Err(LangGraphBackendError::UnsupportedWorkflow);
    };

    let mut output = String::new();
    push_prelude(&mut output, module);
    push_state_type(&mut output, module);
    output.push_str(&format!(
        "AIR_MODULE = {}\n\n",
        py_literal(&serde_json::to_value(module)?)?
    ));
    push_helpers(&mut output);
    push_stubs(&mut output);
    push_rule_functions(&mut output, module)?;
    push_graph_builder(&mut output, module)?;
    Ok(output)
}

pub fn lower_run_plan(
    plan: &RunPlan,
    store: &ModuleStore,
    base_dir: impl AsRef<Path>,
) -> Result<String, LangGraphBackendError> {
    let base_dir = base_dir.as_ref();
    let mut modules = BTreeMap::new();

    for node in &plan.nodes {
        let module_ref = store
            .modules
            .get(&node.module)
            .ok_or_else(|| LangGraphBackendError::UnknownModule(node.module.clone()))?;
        let path = resolve_module_path(base_dir, &node.module, &module_ref.path)?;
        let module = air_parser::parse_air_file(path)?;
        let verification = air_verify::verify(&module);
        if !verification.is_success() {
            return Err(LangGraphBackendError::ModuleVerify {
                module: node.module.clone(),
                diagnostics: verification.diagnostics,
            });
        }
        modules.insert(node.id.clone(), module);
    }
    if let Some(dynamic) = &plan.dynamic {
        for fanout in &dynamic.fanouts {
            if modules.contains_key(&fanout.module) {
                continue;
            }
            let module_ref = store
                .modules
                .get(&fanout.module)
                .ok_or_else(|| LangGraphBackendError::UnknownModule(fanout.module.clone()))?;
            let path = resolve_module_path(base_dir, &fanout.module, &module_ref.path)?;
            let module = air_parser::parse_air_file(path)?;
            let verification = air_verify::verify(&module);
            if !verification.is_success() {
                return Err(LangGraphBackendError::ModuleVerify {
                    module: fanout.module.clone(),
                    diagnostics: verification.diagnostics,
                });
            }
            modules.insert(fanout.module.clone(), module);
        }
    }

    let plan_json = serde_json::to_value(plan)?;
    let modules_json = serde_json::to_value(&modules)?;
    let mut output = String::new();
    output.push_str("# Generated by AIR LangGraph run-plan backend.\n");
    output.push_str(&format!(
        "# Source run plan: {} {}\n\n",
        plan.plan.name, plan.plan.version
    ));
    output.push_str("import json\n");
    output.push_str("import os\n");
    output.push_str("import sys\n");
    output.push_str("import time\n");
    output.push_str("from concurrent.futures import ThreadPoolExecutor, as_completed\n");
    output.push_str("from typing import Any, TypedDict\n");
    output.push_str("from langgraph.graph import StateGraph, START, END\n\n");
    let state_fields = run_plan_state_fields(plan);
    if state_fields.is_empty() {
        output.push_str("class AirState(TypedDict, total=False):\n");
        output.push_str("    pass\n\n");
    } else {
        output.push_str("AirState = TypedDict(\"AirState\", {\n");
        for field in state_fields {
            output.push_str(&format!("    {}: Any,\n", py_string(&field)?));
        }
        output.push_str("}, total=False)\n\n");
    }
    output.push_str(&format!("RUN_PLAN = {}\n", py_literal(&plan_json)?));
    output.push_str(&format!("MODULES = {}\n\n", py_literal(&modules_json)?));
    push_plan_runtime(&mut output);
    push_plan_graph_builder(&mut output, plan)?;
    Ok(output)
}

fn run_plan_state_fields(plan: &RunPlan) -> Vec<String> {
    let mut fields = BTreeMap::new();
    fields.insert("__air_dynamic_materialized".to_string(), ());
    fields.insert("__air_halted".to_string(), ());
    fields.insert("__air_skipped".to_string(), ());
    for node in &plan.nodes {
        fields.insert(node.id.clone(), ());
    }
    for connection in &plan.connect {
        if let Some(field) = connection
            .from
            .as_deref()
            .and_then(|from| from.strip_prefix("$input."))
        {
            fields.insert(field.to_string(), ());
        }
    }
    for output in plan.outputs.keys() {
        fields.insert(output.clone(), ());
    }
    for field in dynamic_run_plan_state_fields(plan) {
        fields.insert(field, ());
    }
    fields.into_keys().collect()
}

fn dynamic_run_plan_state_fields(plan: &RunPlan) -> Vec<String> {
    let Some(dynamic) = &plan.dynamic else {
        return Vec::new();
    };
    let static_nodes = plan
        .nodes
        .iter()
        .map(|node| node.id.as_str())
        .collect::<std::collections::BTreeSet<_>>();
    let mut materialized: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut unresolved = dynamic.fanouts.iter().collect::<Vec<_>>();

    while !unresolved.is_empty() {
        let mut progressed = false;
        let mut next = Vec::new();
        for fanout in unresolved {
            if static_nodes.contains(fanout.after.as_str()) {
                let ids = (0..fanout.max_items)
                    .map(|index| format!("{}_{}", fanout.id_prefix, index + 1))
                    .collect::<Vec<_>>();
                materialized.insert(fanout.id.clone(), ids);
                progressed = true;
            } else if let Some(parent_ids) = materialized.get(&fanout.after) {
                let ids = parent_ids
                    .iter()
                    .enumerate()
                    .flat_map(|(parent_index, _)| {
                        (0..fanout.max_items).map(move |index| {
                            format!("{}_{}_{}", fanout.id_prefix, parent_index + 1, index + 1)
                        })
                    })
                    .collect::<Vec<_>>();
                materialized.insert(fanout.id.clone(), ids);
                progressed = true;
            } else {
                next.push(fanout);
            }
        }
        if !progressed {
            for fanout in next {
                let ids = (0..fanout.max_items)
                    .map(|index| format!("{}_{}", fanout.id_prefix, index + 1))
                    .collect::<Vec<_>>();
                materialized.insert(fanout.id.clone(), ids);
            }
            break;
        }
        unresolved = next;
    }

    materialized
        .into_values()
        .flatten()
        .collect::<Vec<String>>()
}

fn push_prelude(output: &mut String, module: &AirModule) {
    output.push_str("# Generated by AIR LangGraph backend.\n");
    output.push_str(&format!(
        "# Source agent: {} {}\n\n",
        module.agent.name, module.agent.version
    ));
    output.push_str("import json\n");
    output.push_str("import os\n");
    output.push_str("import sys\n");
    output.push_str("from typing import Any, TypedDict\n");
    output.push_str("from langgraph.graph import StateGraph, START, END\n\n");
}

fn push_state_type(output: &mut String, module: &AirModule) {
    output.push_str("class AirState(TypedDict, total=False):\n");
    let mut fields = BTreeMap::new();
    fields.extend(module.inputs.keys().map(|key| (key.as_str(), "Any")));
    fields.extend(module.state.keys().map(|key| (key.as_str(), "Any")));
    fields.extend(module.outputs.keys().map(|key| (key.as_str(), "Any")));
    if fields.is_empty() {
        output.push_str("    pass\n\n");
        return;
    }
    for (field, kind) in fields {
        output.push_str(&format!("    {}: {}\n", py_ident(field), kind));
    }
    output.push('\n');
}

fn push_helpers(output: &mut String) {
    output.push_str(
        r#"def _air_get_path(state: dict[str, Any], path: str) -> Any:
    for prefix in ("input.", "state.", "output.", "outputs."):
        if path.startswith(prefix):
            path = path[len(prefix):]
            break
    path = _air_normalize_path(path)
    value: Any = state
    for segment in path.split("."):
        if isinstance(value, dict):
            value = value[segment]
        elif isinstance(value, list):
            value = value[int(segment)]
        else:
            value = getattr(value, segment)
    return value


def _air_normalize_path(path: str) -> str:
    normalized = ""
    index = 0
    while index < len(path):
        ch = path[index]
        if ch != "[":
            normalized += ch
            index += 1
            continue
        end = path.find("]", index)
        if end == -1:
            raise RuntimeError(f"invalid path {path}")
        segment = path[index + 1:end]
        if not segment.isdigit():
            raise RuntimeError(f"invalid path {path}")
        normalized += "." + segment
        index = end + 1
    return normalized


def _air_template(state: dict[str, Any], template: str) -> str:
    rendered = ""
    rest = template
    while "{{" in rest:
        before, rest = rest.split("{{", 1)
        rendered += before
        if "}}" not in rest:
            return rendered + "{{" + rest
        path, rest = rest.split("}}", 1)
        rendered += str(_air_get_path(state, path.strip()))
    return rendered + rest


def _air_take_last(value: Any, max_items: int) -> list[Any]:
    if not isinstance(value, list):
        raise RuntimeError("take_last expression expected an array value")
    if max_items <= 0:
        raise RuntimeError("take_last max_items must be at least 1")
    return value[-max_items:]


def _air_take_last_within_bytes(value: Any, max_items: int, max_bytes: int) -> list[Any]:
    if not isinstance(value, list):
        raise RuntimeError("take_last_within_bytes expression expected an array value")
    if max_items <= 0:
        raise RuntimeError("take_last_within_bytes max_items must be at least 1")
    if max_bytes <= 0:
        raise RuntimeError("take_last_within_bytes max_bytes must be at least 1")
    selected = []
    selected_bytes = 0
    for item in reversed(value[-max_items:]):
        raw = json.dumps(item)
        candidate = item
        candidate_bytes = len(raw.encode("utf-8"))
        if selected_bytes + candidate_bytes > max_bytes:
            candidate = {"_air_truncated": True}
            candidate_bytes = len(json.dumps(candidate).encode("utf-8"))
        if selected_bytes + candidate_bytes > max_bytes:
            continue
        selected_bytes += candidate_bytes
        selected.append(candidate)
    selected.reverse()
    return selected


def _air_read_path(local_state: dict[str, Any], outputs: dict[str, Any], path: str) -> Any:
    merged = dict(local_state)
    merged.update(outputs)
    return _air_get_path(merged, path)


def _air_parse_condition_literal(raw: str) -> Any:
    raw = raw.strip()
    if not raw:
        raise RuntimeError("unsupported empty condition literal")
    if (raw.startswith("\"") and raw.endswith("\"")) or (raw.startswith("'") and raw.endswith("'")):
        return raw[1:-1]
    return json.loads(raw)


def _air_condition_clause_matches(local_state: dict[str, Any], outputs: dict[str, Any], clause: str) -> bool:
    if "==" in clause:
        left, right = clause.split("==", 1)
        expected_equal = True
    elif "!=" in clause:
        left, right = clause.split("!=", 1)
        expected_equal = False
    else:
        raise RuntimeError(f"unsupported condition clause {clause}")
    actual = _air_read_path(local_state, outputs, left.strip())
    expected = _air_parse_condition_literal(right)
    return (actual == expected) == expected_equal


def _air_condition_matches(local_state: dict[str, Any], outputs: dict[str, Any], condition: str) -> bool:
    for group in condition.split("||"):
        if all(_air_condition_clause_matches(local_state, outputs, clause.strip()) for clause in group.split("&&")):
            return True
    return False


def _air_validate_output(module: dict[str, Any], field: str, value: Any) -> None:
    spec = (
        module.get("state", {}).get(field)
        or module.get("outputs", {}).get(field)
        or module.get("inputs", {}).get(field)
    )
    if spec is None:
        return
    errors = _air_validate_value(field, value, spec)
    if errors:
        raise RuntimeError("AIR schema violation: " + "; ".join(errors))


def _air_validate_value(path: str, value: Any, spec: Any) -> list[str]:
    if isinstance(spec, str):
        return _air_validate_primitive(path, value, spec)
    if not isinstance(spec, dict):
        return []
    kind = spec.get("type")
    if kind in ("string", "integer", "number", "boolean", "object"):
        if kind == "object":
            return _air_validate_object(path, value, spec)
        return _air_validate_primitive(path, value, kind)
    if kind == "array":
        return _air_validate_array(path, value, spec)
    if kind == "enum":
        values = spec.get("enum", [])
        return [] if value in values else [f"{path} expected enum {values} got {value!r}"]
    return []


def _air_validate_primitive(path: str, value: Any, kind: str) -> list[str]:
    valid = (
        (kind == "string" and isinstance(value, str))
        or (kind == "integer" and isinstance(value, int) and not isinstance(value, bool))
        or (kind == "number" and isinstance(value, (int, float)) and not isinstance(value, bool))
        or (kind == "boolean" and isinstance(value, bool))
        or (kind == "object" and isinstance(value, dict))
    )
    return [] if valid else [f"{path} expected {kind} got {_air_value_kind(value)}"]


def _air_validate_object(path: str, value: Any, spec: dict[str, Any]) -> list[str]:
    if not isinstance(value, dict):
        return [f"{path} expected object got {_air_value_kind(value)}"]
    errors: list[str] = []
    for required in spec.get("required", []):
        if required not in value:
            errors.append(f"{path}.{required} missing required field")
    for field, field_spec in spec.get("properties", {}).items():
        if field in value:
            errors.extend(_air_validate_value(f"{path}.{field}", value[field], field_spec))
    if spec.get("additional_properties", True) is False:
        for field in value:
            if field not in spec.get("properties", {}):
                errors.append(f"{path}.{field} unexpected additional field")
    return errors


def _air_validate_array(path: str, value: Any, spec: dict[str, Any]) -> list[str]:
    if not isinstance(value, list):
        return [f"{path} expected array got {_air_value_kind(value)}"]
    errors: list[str] = []
    min_items = spec.get("min_items")
    if min_items is not None and len(value) < min_items:
        errors.append(f"{path} expected at least {min_items} items got {len(value)}")
    max_items = spec.get("max_items")
    if max_items is not None and len(value) > max_items:
        errors.append(f"{path} expected at most {max_items} items got {len(value)}")
    item_spec = spec.get("items")
    if item_spec is None:
        return errors
    for index, item in enumerate(value):
        errors.extend(_air_validate_value(f"{path}[{index}]", item, item_spec))
    return errors


def _air_value_kind(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, str):
        return "string"
    if isinstance(value, (int, float)):
        return "number"
    if isinstance(value, list):
        return "array"
    if isinstance(value, dict):
        return "object"
    return type(value).__name__


"#,
    );
}

fn push_stubs(output: &mut String) {
    output.push_str(
        r#"def call_model(name: str, input_value: Any) -> Any:
    raise NotImplementedError(f"model provider is not wired: {name}")


def call_tool(name: str, input_value: Any) -> Any:
    provider = globals().get("AIR_TOOL_PROVIDER")
    if provider is None:
        raise NotImplementedError(f"tool provider is not wired: {name}")
    return provider(name=name, input_value=input_value)


def request_approval(capabilities: list[str], module: Any = None, state: Any = None) -> dict[str, Any]:
    provider = globals().get("AIR_APPROVAL_PROVIDER")
    if provider is None:
        raise RuntimeError(f"approval provider is not wired: {capabilities}")
    decision = provider(capabilities=capabilities, module=module, state=state)
    if decision is None:
        decision = {}
    if not isinstance(decision, dict):
        raise RuntimeError("approval provider must return a dict")
    if not decision.get("approved", False):
        reason = decision.get("reason", "approval provider denied the request")
        raise RuntimeError(f"approval denied for {capabilities}: {reason}")
    return decision


"#,
    );
}

fn push_rule_functions(
    output: &mut String,
    module: &AirModule,
) -> Result<(), LangGraphBackendError> {
    let Workflow::StateMachine(workflow) = &module.workflow else {
        return Err(LangGraphBackendError::UnsupportedWorkflow);
    };

    output.push_str("def __air_init__(state: AirState) -> dict[str, Any]:\n");
    output.push_str("    if state.get(\"phase\") is None:\n");
    output.push_str(&format!(
        "        return {{\"phase\": {}}}\n",
        py_string(&workflow.initial)?
    ));
    output.push_str("    return {}\n\n");

    for rule in &workflow.rules {
        let function_name = rule_function_name(&rule.id);
        output.push_str(&format!(
            "def {function_name}(state: AirState) -> dict[str, Any]:\n"
        ));
        output.push_str("    working: dict[str, Any] = dict(state)\n");
        output.push_str("    updates: dict[str, Any] = {}\n");
        if rule.actions.is_empty() {
            output.push_str("    return updates\n\n");
            continue;
        }
        for action in &rule.actions {
            push_action(output, action)?;
        }
        output.push_str("    return updates\n\n");
    }

    output.push_str("def __air_route__(state: AirState) -> str:\n");
    output.push_str("    local_state = dict(state)\n");
    output.push_str("    outputs: dict[str, Any] = {}\n");
    for rule in &workflow.rules {
        output.push_str(&format!(
            "    if _air_condition_matches(local_state, outputs, {}):\n        return {}\n",
            py_string(&rule.when)?,
            py_string(&rule.id)?
        ));
    }
    output.push_str("    return \"__end__\"\n\n");

    Ok(())
}

fn push_action(output: &mut String, action: &StateAction) -> Result<(), LangGraphBackendError> {
    match action {
        StateAction::Set { values } => {
            for (key, value) in values {
                output.push_str(&format!(
                    "    updates[{}] = _air_resolve_set_value(working, {{}}, {})\n",
                    py_string(key)?,
                    py_literal(value)?
                ));
                output.push_str(&format!(
                    "    _air_validate_output(AIR_MODULE, {}, updates[{}])\n",
                    py_string(key)?,
                    py_string(key)?
                ));
                output.push_str(&format!(
                    "    working[{}] = updates[{}]\n",
                    py_string(key)?,
                    py_string(key)?
                ));
            }
        }
        StateAction::Append { target, value } => {
            output.push_str(&format!("    input_value = {}\n", input_expr(value)?));
            output.push_str(&format!(
                "    existing = list(working.get({}, []))\n",
                py_string(target)?
            ));
            output.push_str("    existing.append(input_value)\n");
            output.push_str(&format!(
                "    _air_validate_output(AIR_MODULE, {}, existing)\n",
                py_string(target)?
            ));
            output.push_str(&format!("    updates[{}] = existing\n", py_string(target)?));
            output.push_str(&format!(
                "    working[{}] = updates[{}]\n",
                py_string(target)?,
                py_string(target)?
            ));
        }
        StateAction::ModelCall {
            model,
            input,
            output: output_field,
            ..
        } => {
            output.push_str(&format!("    input_value = {}\n", input_expr(input)?));
            output.push_str(&format!(
                "    result_value = call_model({}, input_value)\n",
                py_string(model)?
            ));
            output.push_str(&format!(
                "    _air_validate_output(AIR_MODULE, {}, result_value)\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    updates[{}] = result_value\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    working[{}] = updates[{}]\n",
                py_string(output_field)?,
                py_string(output_field)?
            ));
        }
        StateAction::ToolCall {
            tool,
            input,
            output: output_field,
            ..
        } => {
            output.push_str(&format!("    input_value = {}\n", input_expr(input)?));
            output.push_str(&format!(
                "    result_value = call_tool({}, input_value)\n",
                py_string(tool)?
            ));
            output.push_str(&format!(
                "    _air_validate_output(AIR_MODULE, {}, result_value)\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    updates[{}] = result_value\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    working[{}] = updates[{}]\n",
                py_string(output_field)?,
                py_string(output_field)?
            ));
        }
        StateAction::ToolDispatch {
            input,
            output: output_field,
            ..
        } => {
            output.push_str(&format!("    dispatch_value = {}\n", input_expr(input)?));
            output.push_str("    tool_name = dispatch_value.get(\"tool\") if isinstance(dispatch_value, dict) else None\n");
            output.push_str("    if not isinstance(tool_name, str):\n");
            output.push_str(
                "        raise ValueError(\"tool_dispatch input.tool must be a string\")\n",
            );
            output.push_str("    tool_name, _requested_tool = _air_normalize_model_selected_tool_name(AIR_MODULE, tool_name)\n");
            output.push_str("    tool_input = dispatch_value.get(\"input\", {})\n");
            output.push_str("    result_value = call_tool(tool_name, tool_input)\n");
            output.push_str(&format!(
                "    _air_validate_output(AIR_MODULE, {}, result_value)\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    updates[{}] = result_value\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    working[{}] = updates[{}]\n",
                py_string(output_field)?,
                py_string(output_field)?
            ));
        }
        StateAction::ToolBatchDispatch {
            input,
            output: output_field,
            max_calls,
            on_error,
            ..
        } => {
            let observe_errors = *on_error == ToolErrorMode::Observe;
            output.push_str(&format!("    batch_value = {}\n", input_expr(input)?));
            output.push_str("    if not isinstance(batch_value, list):\n");
            output.push_str(
                "        raise ValueError(\"tool_batch_dispatch input must be an array\")\n",
            );
            output.push_str(&format!("    if len(batch_value) > {}:\n", max_calls));
            output.push_str(&format!(
                "        raise RuntimeError(\"tool_batch_dispatch max_calls exceeded: limit={} attempted={{}}\".format(len(batch_value)))\n",
                max_calls
            ));
            output.push_str("    batch_outputs = []\n");
            output.push_str("    for index, dispatch_value in enumerate(batch_value):\n");
            output.push_str("        tool_name = dispatch_value.get(\"tool\") if isinstance(dispatch_value, dict) else None\n");
            output.push_str("        if not isinstance(tool_name, str):\n");
            output.push_str("            error = ValueError(f\"tool_batch_dispatch input[{index}].tool must be a string\")\n");
            if observe_errors {
                output.push_str("            batch_outputs.append({\"tool\": \"<invalid>\", \"input\": {}, \"status\": \"error\", \"error\": str(error), \"output\": {\"status\": \"error\", \"error\": str(error), \"requested\": dispatch_value}})\n");
                output.push_str("            continue\n");
            } else {
                output.push_str("            raise error\n");
            }
            output.push_str("        tool_name, _requested_tool = _air_normalize_model_selected_tool_name(AIR_MODULE, tool_name)\n");
            output.push_str("        tool_input = dispatch_value.get(\"input\", {})\n");
            output.push_str("        if not any(tool.get(\"name\") == tool_name for tool in AIR_MODULE.get(\"tools\", [])):\n");
            output.push_str("            error = RuntimeError(f\"tool {tool_name} is not declared by module {AIR_MODULE.get('agent', {}).get('name', '<unknown>')}\")\n");
            if observe_errors {
                output.push_str("            batch_outputs.append({\"tool\": tool_name, \"input\": tool_input, \"status\": \"error\", \"error\": str(error), \"output\": {\"status\": \"error\", \"error\": str(error)}})\n");
                output.push_str("            continue\n");
            } else {
                output.push_str("            raise error\n");
            }
            output.push_str("        try:\n");
            output.push_str("            result_value = call_tool(tool_name, tool_input)\n");
            output.push_str("            batch_outputs.append({\"tool\": tool_name, \"input\": tool_input, \"status\": \"ok\", \"output\": result_value})\n");
            output.push_str("        except Exception as error:\n");
            if observe_errors {
                output.push_str("            batch_outputs.append({\"tool\": tool_name, \"input\": tool_input, \"status\": \"error\", \"error\": str(error), \"output\": {\"status\": \"error\", \"error\": str(error)}})\n");
            } else {
                output.push_str("            raise\n");
            }
            output.push_str(&format!(
                "    _air_validate_output(AIR_MODULE, {}, batch_outputs)\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    updates[{}] = batch_outputs\n",
                py_string(output_field)?
            ));
            output.push_str(&format!(
                "    working[{}] = updates[{}]\n",
                py_string(output_field)?,
                py_string(output_field)?
            ));
        }
        StateAction::Approval { approval_for } => {
            output.push_str(&format!(
                "    request_approval({}, AIR_MODULE, working)\n",
                py_literal(&Value::Array(
                    approval_for
                        .iter()
                        .map(|value| Value::String(value.clone()))
                        .collect()
                ))?
            ));
        }
        StateAction::Return { output: field } => {
            output.push_str(&format!(
                "    updates[{}] = _air_get_path(working, {})\n",
                py_string(field)?,
                py_string(field)?
            ));
            output.push_str(&format!(
                "    working[{}] = updates[{}]\n",
                py_string(field)?,
                py_string(field)?
            ));
        }
    }
    Ok(())
}

fn push_graph_builder(
    output: &mut String,
    module: &AirModule,
) -> Result<(), LangGraphBackendError> {
    let Workflow::StateMachine(workflow) = &module.workflow else {
        return Err(LangGraphBackendError::UnsupportedWorkflow);
    };

    output.push_str("graph_builder = StateGraph(AirState)\n");
    output.push_str("graph_builder.add_node(\"__air_init__\", __air_init__)\n");
    for rule in &workflow.rules {
        output.push_str(&format!(
            "graph_builder.add_node({}, {})\n",
            py_string(&rule.id)?,
            rule_function_name(&rule.id)
        ));
    }

    output.push_str("graph_builder.add_edge(START, \"__air_init__\")\n");
    let route_map = route_map(module)?;
    output.push_str(&format!(
        "graph_builder.add_conditional_edges(\"__air_init__\", __air_route__, {})\n",
        py_dict_literal(&route_map)?
    ));
    for rule in &workflow.rules {
        if condition_phase_literal(&rule.when)
            .as_ref()
            .is_some_and(|phase| workflow.terminal.iter().any(|terminal| terminal == phase))
        {
            output.push_str(&format!(
                "graph_builder.add_edge({}, END)\n",
                py_string(&rule.id)?
            ));
        } else {
            output.push_str(&format!(
                "graph_builder.add_conditional_edges({}, __air_route__, {})\n",
                py_string(&rule.id)?,
                py_dict_literal(&route_map)?
            ));
        }
    }
    output.push_str("graph = graph_builder.compile()\n");
    Ok(())
}

