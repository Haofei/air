fn js_optional_string(value: Option<&str>) -> String {
    value.map(js_string).unwrap_or_else(|| "null".to_string())
}

fn js_string(value: &str) -> String {
    serde_json_escape(value)
}

fn serde_json_escape(value: &str) -> String {
    let mut output = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            ch => output.push(ch),
        }
    }
    output.push('"');
    output
}

fn escape_template(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('`', "\\`")
        .replace("${", "\\${")
}

fn to_sdk_tool_name(name: &str) -> String {
    name.chars()
        .map(|ch| {
            if ch == '_' || ch.is_ascii_alphanumeric() {
                ch
            } else {
                '_'
            }
        })
        .collect()
}

fn output_contract(module: &AirModule, return_output: Option<&str>) -> String {
    if let Some(output_name) = return_output {
        if let Some(spec) = module
            .outputs
            .get(output_name)
            .or_else(|| module.state.get(output_name))
        {
            return describe_type(spec);
        }
    }

    if module.outputs.is_empty() {
        return "any JSON value".to_string();
    }

    format!(
        "object with top-level keys [{}]",
        module
            .outputs
            .keys()
            .map(String::as_str)
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn describe_type(spec: &TypeSpec) -> String {
    match spec {
        TypeSpec::Shorthand(kind) => kind.kind_name().to_string(),
        TypeSpec::Detailed(detailed) => match detailed.kind {
            DetailedTypeKind::Object => {
                if detailed.required.is_empty() && detailed.properties.is_empty() {
                    return "object".to_string();
                }

                let required = if detailed.required.is_empty() {
                    "no required keys".to_string()
                } else {
                    format!("required keys [{}]", detailed.required.join(", "))
                };
                let properties = if detailed.properties.is_empty() {
                    "any properties".to_string()
                } else {
                    let entries = detailed
                        .properties
                        .iter()
                        .map(|(name, spec)| format!("{name}: {}", describe_type(spec)))
                        .collect::<Vec<_>>()
                        .join(", ");
                    format!("properties {{{entries}}}")
                };
                format!("object with {required}; {properties}")
            }
            DetailedTypeKind::Array => detailed
                .items
                .as_deref()
                .map(|items| format!("array of {}", describe_type(items)))
                .unwrap_or_else(|| "array".to_string()),
            DetailedTypeKind::Enum => {
                if detailed.enum_values.is_empty() {
                    "enum".to_string()
                } else {
                    format!("enum [{}]", detailed.enum_values.join(", "))
                }
            }
            _ => detailed.kind.kind_name().to_string(),
        },
    }
}

fn escape_single_quoted_js(value: &str) -> String {
    value.replace('\\', "\\\\").replace('\'', "\\'")
}

