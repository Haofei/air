#[derive(Debug, Error)]
pub enum OpenAiAgentsJsBackendError {
    #[error("OpenAI Agents JS semantic backend only supports state_machine workflow lowering")]
    UnsupportedWorkflow,

    #[error("OpenAI Agents JS semantic backend requires at least one model_call action")]
    MissingModelCall,

    #[error("OpenAI Agents JS semantic backend currently supports at most one tool_call action")]
    TooManyToolCalls,

    #[error("failed to parse AIR module: {0}")]
    ModuleParse(#[from] air_parser::ParseError),

    #[error(transparent)]
    Linker(#[from] air_linker::LinkerError),

    #[error("failed to serialize JSON: {0}")]
    Json(#[from] serde_json::Error),

    #[error("run plan references unknown module {0}")]
    UnknownModule(String),

    #[error("module {module} failed verification: {diagnostics:?}")]
    ModuleVerify {
        module: String,
        diagnostics: Vec<air_core::Diagnostic>,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct SemanticPlan {
    model_alias: String,
    tool_name: Option<String>,
    primary_input: String,
    output_field: Option<String>,
    output_contract: String,
}

pub fn lower_module(module: &AirModule) -> Result<String, OpenAiAgentsJsBackendError> {
    let plan = semantic_plan(module)?;
    let mut output = String::new();
    push_prelude(&mut output, module);
    output.push_str(&format!(
        "const AIR_MODULE = {};\n\n",
        serde_json::to_string_pretty(module)?
    ));
    push_runtime_helpers(&mut output);
    push_main(&mut output, module, &plan);
    Ok(output)
}

pub fn lower_run_plan_strict(
    plan: &RunPlan,
    store: &ModuleStore,
    base_dir: impl AsRef<Path>,
) -> Result<String, OpenAiAgentsJsBackendError> {
    let base_dir = base_dir.as_ref();
    let mut modules = BTreeMap::new();

    for node in &plan.nodes {
        let module_ref = store
            .modules
            .get(&node.module)
            .ok_or_else(|| OpenAiAgentsJsBackendError::UnknownModule(node.module.clone()))?;
        let path = resolve_module_path(base_dir, &node.module, &module_ref.path)?;
        let module = air_parser::parse_air_file(path)?;
        let verification = air_verify::verify(&module);
        if !verification.is_success() {
            return Err(OpenAiAgentsJsBackendError::ModuleVerify {
                module: node.module.clone(),
                diagnostics: verification.diagnostics,
            });
        }
        modules.insert(node.id.clone(), module);
    }
    if let Some(dynamic) = &plan.dynamic {
        for fanout in &dynamic.fanouts {
            if modules.contains_key(&fanout.module) {
                continue;
            }
            let module_ref = store
                .modules
                .get(&fanout.module)
                .ok_or_else(|| OpenAiAgentsJsBackendError::UnknownModule(fanout.module.clone()))?;
            let path = resolve_module_path(base_dir, &fanout.module, &module_ref.path)?;
            let module = air_parser::parse_air_file(path)?;
            let verification = air_verify::verify(&module);
            if !verification.is_success() {
                return Err(OpenAiAgentsJsBackendError::ModuleVerify {
                    module: fanout.module.clone(),
                    diagnostics: verification.diagnostics,
                });
            }
            modules.insert(fanout.module.clone(), module);
        }
    }

    let mut output = String::new();
    output.push_str("// Generated by AIR OpenAI JS strict run-plan backend.\n");
    output
        .push_str("// This preserves RunPlan module order and per-module state-machine actions.\n");
    output.push_str(&format!(
        "// Source run plan: {} {}\n\n",
        plan.plan.name, plan.plan.version
    ));
    output.push_str("import fs from 'node:fs';\n");
    output.push_str("import OpenAI from 'openai';\n\n");
    output.push_str(&format!(
        "const RUN_PLAN = {};\n",
        serde_json::to_string_pretty(plan)?
    ));
    output.push_str(&format!(
        "const MODULES = {};\n\n",
        serde_json::to_string_pretty(&modules)?
    ));
    push_strict_js_runtime(&mut output);
    Ok(output)
}

fn semantic_plan(module: &AirModule) -> Result<SemanticPlan, OpenAiAgentsJsBackendError> {
    let Workflow::StateMachine(workflow) = &module.workflow else {
        return Err(OpenAiAgentsJsBackendError::UnsupportedWorkflow);
    };

    let mut model_alias = None;
    let mut tool_name = None;
    let mut return_output = None;

    for action in workflow.rules.iter().flat_map(|rule| &rule.actions) {
        match action {
            StateAction::ModelCall { model, .. } if model_alias.is_none() => {
                model_alias = Some(model.clone());
            }
            StateAction::ToolCall { tool, .. } if tool_name.replace(tool.clone()).is_some() => {
                return Err(OpenAiAgentsJsBackendError::TooManyToolCalls);
            }
            StateAction::ToolCall { .. } => {}
            StateAction::ToolDispatch { .. } | StateAction::ToolBatchDispatch { .. } => {
                return Err(OpenAiAgentsJsBackendError::TooManyToolCalls);
            }
            StateAction::Return { output } if return_output.is_none() => {
                return_output = Some(output.clone());
            }
            _ => {}
        }
    }

    let Some(model_alias) = model_alias else {
        return Err(OpenAiAgentsJsBackendError::MissingModelCall);
    };

    let primary_input = module
        .inputs
        .keys()
        .next()
        .cloned()
        .unwrap_or_else(|| "input".to_string());

    Ok(SemanticPlan {
        model_alias,
        tool_name,
        primary_input,
        output_field: return_output.clone(),
        output_contract: output_contract(module, return_output.as_deref()),
    })
}

